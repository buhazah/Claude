# ── Extraction ────────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    ("suffix", "expected"),
    [
        (".pdf", SourceKind.PDF),
        (".md", SourceKind.MARKDOWN),
        (".PY", SourceKind.CODE),
        (".xlsx", SourceKind.XLSX),
        (".png", SourceKind.IMAGE),
        (".wat", SourceKind.UNKNOWN),
    ],
)
def test_suffixes_map_to_kinds(suffix: str, expected: SourceKind) -> None:
    assert kind_for(suffix) is expected


def test_pdf_pages_become_located_blocks(pdf_file: Path) -> None:
    extracted = extract_path(pdf_file)

    assert extracted.kind is SourceKind.PDF
    assert [b.locator for b in extracted.blocks] == ["p. 1", "p. 2"]
    assert "4.2 million" in extracted.blocks[0].text
    assert "Churn" in extracted.blocks[1].text


def test_docx_headings_become_locators_and_tables_survive(docx_file: Path) -> None:
    extracted = extract_path(docx_file)
    locators = {b.locator for b in extracted.blocks}

    assert "Pricing Policy" in locators
    assert "Discounts" in locators
    # The numbers people search for usually live in tables.
    table_block = next(b for b in extracted.blocks if b.locator.startswith("table"))
    assert "Pro | 49" in table_block.text


def test_pptx_slides_are_numbered(pptx_file: Path) -> None:
    extracted = extract_path(pptx_file)

    assert [b.locator for b in extracted.blocks] == ["slide 1", "slide 2"]
    assert "German market" in extracted.blocks[0].text
    assert extracted.metadata["slides"] == "2"


def test_xlsx_sheets_carry_cell_ranges(xlsx_file: Path) -> None:
    extracted = extract_path(xlsx_file)
    locators = [b.locator for b in extracted.blocks]

    assert any(loc.startswith("Revenue!") for loc in locators)
    assert any(loc.startswith("Headcount!") for loc in locators)
    assert "138000" in extracted.text


def test_markdown_sections_become_locators(tmp_path: Path) -> None:
    path = tmp_path / "notes.md"
    path.write_text(
        "# Roadmap\n\nIntro line.\n\n## Q3\n\nShip the API.\n\n## Q4\n\nHire two engineers."
    )

    extracted = extract_path(path)
    assert extracted.title == "Roadmap"
    assert {b.locator for b in extracted.blocks} == {"Roadmap", "Q3", "Q4"}


def test_code_blocks_cite_line_spans(tmp_path: Path) -> None:
    path = tmp_path / "service.py"
    path.write_text("\n".join(f"line_{i} = {i}" for i in range(200)))

    extracted = extract_path(path)
    assert extracted.kind is SourceKind.CODE
    assert extracted.blocks[0].locator == "lines 1–80"
    assert extracted.blocks[-1].locator.startswith("lines 161")


def test_csv_repeats_the_header_in_every_block(tmp_path: Path) -> None:
    path = tmp_path / "rows.csv"
    rows = ["name,amount"] + [f"customer{i},{i * 10}" for i in range(120)]
    path.write_text("\n".join(rows))

    extracted = extract_path(path)
    assert len(extracted.blocks) > 1
    # A row of numbers without its column names is unusable once retrieved.
    for block in extracted.blocks:
        assert block.text.startswith("name | amount")


def test_html_headings_become_locators_and_scripts_are_dropped() -> None:
    blocks = html_blocks(
        "<html><head><style>.a{color:red}</style></head><body>"
        "<h1>Terms</h1><p>Payment is due in 30 days.</p>"
        "<script>alert('x')</script><h2>Liability</h2><p>Capped at fees paid.</p>"
        "</body></html>"
    )
    assert [b.locator for b in blocks] == ["Terms", "Liability"]
    assert not any("alert" in b.text for b in blocks)
    assert "30 days" in blocks[0].text


def test_html_entities_are_decoded() -> None:
    blocks = html_blocks("<p>Tom &amp; Jerry &lt;3</p>")
    assert "Tom & Jerry <3" in blocks[0].text


