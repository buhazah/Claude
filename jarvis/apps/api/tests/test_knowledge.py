async def test_ingesting_a_directory_reads_what_it_can(knowledge, tmp_path: Path) -> None:
    folder = tmp_path / "project"
    (folder / ".git").mkdir(parents=True)
    (folder / ".git" / "config").write_text("should be skipped")
    (folder / "README.md").write_text("# Project\n\nIt does the thing.")
    (folder / "main.py").write_text("def run():\n    return 42\n")
    (folder / "logo.png").write_bytes(b"\x89PNG\r\n\x1a\n")

    result = await Ingestor(knowledge).ingest_directory(folder)
    titles = {d.title for d in result.documents}

    assert "Project" in titles
    assert "main.py" in titles
    # Skipped for a stated reason, rather than silently producing nothing.
    assert any("vision" in reason for reason in result.skipped.values())
    assert not any(".git" in source for source in result.skipped)


