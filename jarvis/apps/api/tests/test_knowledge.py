@pytest.fixture(params=["memory", "sqlite"])
async def knowledge(request: pytest.FixtureRequest, tmp_path: Path, clock):
    """The same contract against both stores."""
    if request.param == "memory":
        yield InMemoryKnowledgeStore(clock=clock)
        return
    db = Database(f"sqlite+aiosqlite:///{tmp_path}/kb.db")
    await db.create_all()
    try:
        yield SqlKnowledgeStore(db, clock=clock)
    finally:
        await db.dispose()


async def test_ingesting_a_pdf_makes_it_searchable_with_a_page_citation(
    knowledge, pdf_file: Path
) -> None:
    result = await Ingestor(knowledge).ingest_file(pdf_file)
    assert len(result.documents) == 1

    citations = await knowledge.search("what was quarterly revenue")
    assert citations
    assert "4.2 million" in citations[0].snippet
    # Both pages are small enough to pack into one chunk, so the citation
    # covers the span it actually contains rather than only its first page.
    assert citations[0].locator == "pp. 1–2"
    assert citations[0].reference() == "report.pdf, pp. 1–2"


async def test_a_spreadsheet_is_searchable_by_its_numbers(knowledge, xlsx_file: Path) -> None:
    await Ingestor(knowledge).ingest_file(xlsx_file)
    citations = await knowledge.search("February revenue")

    assert citations
    assert "138000" in citations[0].snippet
    assert citations[0].locator.startswith("Revenue!")


async def test_citations_expose_the_signals_behind_them(knowledge, docx_file: Path) -> None:
    await Ingestor(knowledge).ingest_file(docx_file)
    citations = await knowledge.search("annual prepayment discount")

