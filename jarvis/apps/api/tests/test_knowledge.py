async def test_a_url_is_ingested_with_its_title(knowledge, monkeypatch) -> None:
    import httpx

    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(
            200,
            text="<title>Acme Pricing</title><body><h1>Plans</h1><p>Pro is $49 a month.</p></body>",
        )

    transport = httpx.MockTransport(handler)
    original = httpx.AsyncClient
    monkeypatch.setattr(
        httpx, "AsyncClient", lambda *a, **k: original(*a, **{**k, "transport": transport})
    )

    result = await Ingestor(knowledge).ingest_url("https://acme.test/pricing")
    assert result.documents[0].title == "Acme Pricing"

    citations = await knowledge.search("how much is Pro")
    assert "$49" in citations[0].snippet
    assert citations[0].source == "https://acme.test/pricing"


