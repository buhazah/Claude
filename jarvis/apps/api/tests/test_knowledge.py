@pytest.fixture
def pdf_file(tmp_path: Path) -> Path:
    from pypdf import PdfWriter

    # pypdf cannot author text, so build a minimal but genuine PDF by hand and
    # let pypdf read it — the parser is what is under test.
    path = tmp_path / "report.pdf"
    pages = []
    for number, body in enumerate(
        ["Quarterly revenue reached 4.2 million dollars.", "Churn fell to 2.1 percent."], start=1
    ):
        stream = f"BT /F1 12 Tf 72 720 Td ({body}) Tj ET".encode()
        pages.append((number, stream))

    objects: list[bytes] = []
    kids = " ".join(f"{4 + i * 2} 0 R" for i in range(len(pages)))
    objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    objects.append(f"<< /Type /Pages /Kids [{kids}] /Count {len(pages)} >>".encode())
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    for _, stream in pages:
        objects.append(
            f"<< /Type /Page /Parent 2 0 R /Resources << /Font << /F1 3 0 R >> >> "
            f"/MediaBox [0 0 612 792] /Contents {len(objects) + 2} 0 R >>".encode()
        )
        objects.append(f"<< /Length {len(stream)} >>\nstream\n".encode() + stream + b"\nendstream")

    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for index, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{index} 0 obj\n".encode() + body + b"\nendobj\n"

    xref_at = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode() + b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_at}\n%%EOF".encode()
    )

    path.write_bytes(bytes(out))
    PdfWriter(clone_from=str(path))  # fails loudly if the file is not a real PDF
    return path


