async def test_ingestion_publishes_an_event(clock) -> None:
    from jarvis.kernel.bus import EventBus

    bus = EventBus(clock=clock)
    store = InMemoryKnowledgeStore(bus=bus, clock=clock)
    sub = bus.subscribe("knowledge.**")

    await Ingestor(store).ingest_text("A note worth keeping.", title="Note")

    assert sub.queue.get_nowait().topic == "knowledge.ingested"


def test_fingerprints_are_content_addressed() -> None:
    assert fingerprint("same") == fingerprint("same")
    assert fingerprint("same") != fingerprint("different")


async def test_documents_survive_a_reconnect(tmp_path: Path, clock) -> None:
    url = f"sqlite+aiosqlite:///{tmp_path}/durable-kb.db"
    first = Database(url)
    await first.create_all()
    await Ingestor(SqlKnowledgeStore(first, clock=clock)).ingest_text(
        "The launch date is 12 September.", title="Launch"
    )
    await first.dispose()

    second = Database(url)
    citations = await SqlKnowledgeStore(second, clock=clock).search("when is launch")
    await second.dispose()

    assert citations and "12 September" in citations[0].snippet
