# ── Chunking ──────────────────────────────────────────────────────────────────


def test_small_blocks_are_packed_together() -> None:
    blocks = [Block(text=f"Paragraph {i}. " * 5, locator=f"p. {i}", order=i) for i in range(1, 4)]
    chunks = chunk_blocks(blocks)

    assert len(chunks) == 1
    # The locator must describe everything in the chunk, not just its first block.
    assert chunks[0].locator == "pp. 1–3"


def test_slides_get_their_own_range_form() -> None:
    blocks = [Block(text="x" * 100, locator=f"slide {i}", order=i) for i in range(1, 4)]
    assert chunk_blocks(blocks)[0].locator == "slides 1–3"


def test_mixed_locators_are_joined_honestly() -> None:
    blocks = [
        Block(text="a" * 100, locator="Overview", order=0),
        Block(text="b" * 100, locator="Risks", order=1),
    ]
    assert chunk_blocks(blocks)[0].locator == "Overview; Risks"


def test_an_oversized_block_is_split_with_part_numbers() -> None:
    """A citation must never claim more than the passage it points at."""
    huge = "\n\n".join(f"Paragraph {i}. " + "word " * 200 for i in range(12))
    chunks = chunk_blocks([Block(text=huge, locator="p. 7", order=0)])

    assert len(chunks) > 1
    assert all(c.locator.startswith("p. 7 (part ") for c in chunks)
    assert all(len(c.content) <= TARGET_CHARS + 400 for c in chunks)


def test_a_tiny_tail_joins_its_neighbour_rather_than_standing_alone() -> None:
    blocks = [
        Block(text="x" * (TARGET_CHARS - 100), locator="p. 1", order=0),
        Block(text="tiny", locator="p. 2", order=1),
    ]
    chunks = chunk_blocks(blocks)
    assert "tiny" in chunks[-1].content


def test_chunks_are_positioned_and_sized() -> None:
    blocks = [Block(text="word " * 400, locator=f"p. {i}", order=i) for i in range(1, 8)]
    chunks = chunk_blocks(blocks, document_id="doc_1")

    assert [c.position for c in chunks] == list(range(len(chunks)))
    assert all(c.document_id == "doc_1" for c in chunks)
    assert all(c.tokens > 0 for c in chunks)


def test_empty_input_produces_no_chunks() -> None:
    assert chunk_blocks([]) == []
    assert chunk_blocks([Block(text="   ", locator="p. 1")]) == []


